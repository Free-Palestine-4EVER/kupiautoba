export function getModelsForMake(makeValue: string): string[] {
  const make = carMakes.find(m => m.value === makeValue || m.label.toLowerCase() === makeValue.toLowerCase());
  return make?.models || [];
}

export function findMakeByLabel(label: string): typeof carMakes[number] | undefined {
  return carMakes.find(m => m.label.toLowerCase() === label.toLowerCase());
}
